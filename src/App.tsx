import React, { useState, useRef } from 'react';
import { GoogleGenAI } from "@google/genai";
import { 
  Upload, 
  Download, 
  RefreshCw, 
  Layers, 
  Zap, 
  Palette, 
  Maximize2,
  CheckCircle2,
  AlertCircle,
  Settings2,
  Box,
  Monitor
} from 'lucide-react';
import { motion, AnimatePresence } from 'motion/react';

type GenerationStyle = 'Pixel Art' | 'Hand-drawn' | 'Vector' | '3D Render';

export default function App() {
  const [originalImage, setOriginalImage] = useState<string | null>(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [spriteSheet, setSpriteSheet] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [selectedStyle, setSelectedStyle] = useState<GenerationStyle>('Pixel Art');
  const [progress, setProgress] = useState(0);

  const fileInputRef = useRef<HTMLInputElement>(null);

  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      const reader = new FileReader();
      reader.onload = (event) => {
        setOriginalImage(event.target?.result as string);
        setSpriteSheet(null);
        setError(null);
      };
      reader.readAsDataURL(file);
    }
  };

  const generateSpriteSheet = async () => {
    if (!originalImage) return;

    setIsGenerating(true);
    setError(null);
    setProgress(10);

    try {
      const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY || '' });
      
      const base64Data = originalImage.split(',')[1];
      const mimeType = originalImage.split(';')[0].split(':')[1];

      setProgress(30);

      const prompt = `Generate a high-quality 2D fighting game character sprite sheet based on the character in this image.
      
      Requirements:
      1. STYLE: ${selectedStyle}. maintain perfect consistency with the original character design.
      2. LAYOUT: A grid of 4 columns and 4 rows (4x4).
      3. POSES:
         - Row 1: Idle animation (4 frames)
         - Row 2: Walk/Run animation (4 frames)
         - Row 3: Attack/Punch animation (4 frames)
         - Row 4: Hurt/Die/Jump poses (4 frames)
      4. BACKGROUND: Clean solid white background (for easy transparency removal).
      5. COMPOSITION: Centered sheet, clear spacing between frames.
      6. QUALITY: High resolution, sharp lines, consistent lighting.`;

      const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash-image',
        contents: {
          parts: [
            {
              inlineData: {
                data: base64Data,
                mimeType: mimeType,
              },
            },
            {
              text: prompt,
            },
          ],
        },
      });

      setProgress(80);

      let foundImage = false;
      const candidates = (response as any).candidates;
      if (candidates && candidates[0]?.content?.parts) {
        for (const part of candidates[0].content.parts) {
          if (part.inlineData) {
            setSpriteSheet(`data:image/png;base64,${part.inlineData.data}`);
            foundImage = true;
            break;
          }
        }
      }

      if (!foundImage) {
        throw new Error("No image was generated by the model. Try again with a clearer character image.");
      }

      setProgress(100);
    } catch (err: any) {
      console.error("Generation error:", err);
      setError(err.message || "Failed to generate sprite sheet. Please check your API key and try again.");
    } finally {
      setIsGenerating(false);
    }
  };

  const downloadSheet = () => {
    if (!spriteSheet) return;
    const link = document.createElement('a');
    link.href = spriteSheet;
    link.download = 'sprite_sheet.png';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="h-screen w-full bg-brand-bg text-slate-300 font-sans flex flex-col overflow-hidden selection:bg-indigo-500/30">
      {/* Top Navigation Bar */}
      <nav className="h-14 border-b border-white/5 flex items-center justify-between px-6 bg-brand-nav shrink-0">
        <div className="flex items-center gap-3">
          <div className="w-6 h-6 bg-indigo-500 rounded-sm flex items-center justify-center font-bold text-white text-xs italic">S</div>
          <span className="font-medium text-white tracking-tight flex items-center">
            SPRITE<span className="text-indigo-400">FORGE</span> 
            <span className="text-[10px] bg-indigo-500/10 text-indigo-400 border border-indigo-500/20 px-1.5 py-0.5 rounded ml-2 uppercase font-bold tracking-widest leading-none">Studio v2.4</span>
          </span>
        </div>
        <div className="flex items-center gap-8">
          <div className="hidden md:flex gap-6 text-[11px] font-bold uppercase tracking-widest text-slate-500">
            <span className="text-indigo-400 border-b-2 border-indigo-400 pb-1 cursor-pointer">Editor</span>
            <span className="hover:text-slate-300 transition-colors cursor-pointer">Library</span>
            <span className="hover:text-slate-300 transition-colors cursor-pointer">Marketplace</span>
          </div>
          <button 
            onClick={downloadSheet}
            className={`
              text-xs font-bold px-5 py-2 rounded transition-all uppercase tracking-wider
              ${spriteSheet ? 'bg-indigo-600 hover:bg-indigo-500 text-white cursor-pointer shadow-lg shadow-indigo-600/20 active:scale-95' : 'bg-white/5 text-slate-600 cursor-not-allowed'}
            `}
          >
            Export Sheet
          </button>
        </div>
      </nav>

      {/* Main Workspace */}
      <div className="flex-1 flex overflow-hidden">
        {/* Sidebar Tools */}
        <aside className="w-72 border-r border-white/5 bg-brand-sidebar flex flex-col shrink-0 overflow-y-auto">
          <div className="p-6 space-y-8 flex-1">
            {/* Source Section */}
            <section>
              <label className="text-[10px] uppercase tracking-widest text-slate-500 font-bold mb-4 block">Source Character</label>
              <div 
                onClick={() => fileInputRef.current?.click()}
                className={`
                  aspect-square bg-white/5 rounded-lg border-2 border-dashed transition-all cursor-pointer flex flex-col items-center justify-center gap-3 group overflow-hidden relative
                  ${originalImage ? 'border-indigo-500/40 bg-indigo-500/5' : 'border-white/10 hover:border-indigo-500/30'}
                `}
              >
                <input 
                  type="file" 
                  ref={fileInputRef} 
                  onChange={handleFileUpload} 
                  className="hidden" 
                  accept="image/*"
                />
                {originalImage ? (
                  <img src={originalImage} alt="Source" className="w-full h-full object-contain p-4" referrerPolicy="no-referrer" />
                ) : (
                  <>
                    <div className="w-10 h-10 rounded-full bg-white/5 flex items-center justify-center text-slate-500 group-hover:scale-110 group-hover:bg-indigo-500/10 transition-all">
                      <Upload className="w-5 h-5" />
                    </div>
                    <span className="text-[10px] text-slate-500 uppercase font-bold tracking-tight">Drop base sprite</span>
                  </>
                )}
                <div className="absolute inset-0 bg-black/60 opacity-0 group-hover:opacity-100 transition-opacity flex items-center justify-center">
                  <span className="text-[10px] uppercase font-bold text-white tracking-widest">{originalImage ? 'Change Image' : 'Select File'}</span>
                </div>
              </div>
              {originalImage && (
                <p className="mt-3 text-[10px] text-slate-600 italic font-mono uppercase truncate flex items-center gap-1.5">
                  <CheckCircle2 className="w-3 h-3 text-indigo-500/60" /> Active Layer Selected
                </p>
              )}
            </section>

            {/* Parameters */}
            <section className="space-y-4">
              <label className="text-[10px] uppercase tracking-widest text-slate-500 font-bold block">Art Style Selection</label>
              <div className="grid grid-cols-2 gap-2">
                {(['Pixel Art', 'Hand-drawn', 'Vector', '3D Render'] as GenerationStyle[]).map((style) => (
                  <button
                    key={style}
                    onClick={() => setSelectedStyle(style)}
                    className={`
                      px-2 py-2.5 text-[10px] font-bold rounded border transition-all uppercase tracking-tight
                      ${selectedStyle === style 
                        ? 'bg-indigo-500/20 border-indigo-500/50 text-indigo-300' 
                        : 'bg-white/5 border-white/10 text-slate-500 hover:bg-white/10 hover:text-slate-300'}
                    `}
                  >
                    {style}
                  </button>
                ))}
              </div>
            </section>

            <section className="space-y-4">
              <label className="text-[10px] uppercase tracking-widest text-slate-500 font-bold block">Animation Cycles</label>
              <div className="space-y-1.5">
                {[
                  { name: 'Idle Cycle', frames: 4, active: true },
                  { name: 'Walk Cycle', frames: 4, active: true },
                  { name: 'Attack A', frames: 4, active: true },
                  { name: 'Hurt/Reaction', frames: 4, active: true },
                ].map((cycle, i) => (
                  <div 
                    key={i} 
                    className={`flex items-center justify-between text-[11px] p-2 rounded border transition-colors ${cycle.active ? 'bg-indigo-500/10 border-indigo-500/20 text-indigo-300' : 'bg-white/5 border-transparent text-slate-500'}`}
                  >
                    <span className="font-medium">{cycle.name} ({cycle.frames}F)</span>
                    <div className="w-3 h-3 rounded-sm border border-indigo-500 flex items-center justify-center">
                      <div className="w-2 h-2 bg-indigo-500"></div>
                    </div>
                  </div>
                ))}
              </div>
            </section>

            {error && (
              <div className="p-4 rounded-lg bg-red-500/5 border border-red-500/20 flex items-start gap-3">
                <AlertCircle className="w-4 h-4 text-red-500 shrink-0" />
                <p className="text-[10px] text-red-400 font-mono leading-relaxed">{error}</p>
              </div>
            )}
          </div>

          <div className="mt-auto p-6 border-t border-white/5 bg-black/20">
            <button 
              id="generate-button"
              disabled={!originalImage || isGenerating}
              onClick={generateSpriteSheet}
              className={`
                w-full text-[11px] font-bold py-4 rounded uppercase tracking-widest transition-all flex items-center justify-center gap-2
                ${!originalImage || isGenerating 
                  ? 'bg-white/5 text-slate-600 cursor-not-allowed border border-white/5' 
                  : 'bg-indigo-600 hover:bg-indigo-500 text-white border-t border-white/20 shadow-xl shadow-indigo-600/10'}
              `}
            >
              {isGenerating ? (
                <>
                  <RefreshCw className="w-4 h-4 animate-spin" />
                  Generating...
                </>
              ) : (
                <>
                  <Zap className="w-4 h-4 fill-white" />
                  Generate All Frames
                </>
              )}
            </button>
          </div>
        </aside>

        {/* Preview Area */}
        <main className="flex-1 bg-brand-canvas flex flex-col relative overflow-hidden">
          <div className="absolute inset-0 opacity-[0.03] pointer-events-none select-none"
               style={{ backgroundImage: 'radial-gradient(#fff 1px, transparent 1px)', backgroundSize: '16px 16px' }}></div>
          
          <div className="p-10 flex-1 flex flex-col overflow-y-auto relative z-10">
            <div className="flex items-center justify-between mb-8">
              <div>
                <h2 className="text-white text-xl font-light tracking-tight flex items-center gap-2">
                  <Monitor className="w-5 h-5 text-indigo-400" />
                  Sprite Sheet Preview
                </h2>
                <p className="text-slate-500 text-[10px] font-mono mt-1 uppercase tracking-widest">Format: PNG-32 Alpha | Output: 4x4 Animation Grid</p>
              </div>
              <div className="flex gap-2">
                <div className="px-3 py-1.5 bg-[#141417] border border-white/10 rounded-full text-[10px] text-slate-400 flex items-center gap-2">
                  <span className="w-1 h-1 rounded-full bg-slate-600"></span> Zoom: 100%
                </div>
                <div className="px-3 py-1.5 bg-[#141417] border border-white/10 rounded-full text-[10px] text-slate-400 flex items-center gap-2">
                  <Settings2 className="w-3 h-3" /> Grid Guides: On
                </div>
              </div>
            </div>

            {/* The Canvas Content */}
            <div className="flex-1 flex items-center justify-center min-h-[400px]">
              <AnimatePresence mode="wait">
                {isGenerating ? (
                  <motion.div 
                    key="loading"
                    initial={{ opacity: 0 }}
                    animate={{ opacity: 1 }}
                    exit={{ opacity: 0 }}
                    className="flex flex-col items-center gap-6"
                  >
                    <div className="relative">
                      <div className="w-24 h-24 rounded-full border-2 border-indigo-500/10 border-t-indigo-500 animate-spin" />
                      <Box className="w-10 h-10 text-indigo-500 absolute inset-0 m-auto animate-pulse" />
                    </div>
                    <div className="text-center space-y-1">
                      <p className="text-[11px] font-bold uppercase tracking-[0.2em] text-indigo-400">Synthesizing Frames</p>
                      <p className="text-[10px] text-slate-500 font-mono bg-white/5 px-2 py-1 rounded">Rendering {selectedStyle} poses...</p>
                    </div>
                  </motion.div>
                ) : spriteSheet ? (
                  <motion.div 
                    key="result"
                    initial={{ opacity: 0, y: 20 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="bg-brand-container border border-white/5 shadow-2xl rounded p-6 w-fit relative group"
                  >
                    <img 
                      src={spriteSheet} 
                      alt="Generated" 
                      id="result-image"
                      className="max-w-full h-auto bg-white rounded-sm" 
                      referrerPolicy="no-referrer"
                    />
                    
                    {/* Horizontal Guide Labels */}
                    <div className="mt-4 flex justify-between px-2 opacity-30 text-[8px] font-mono tracking-[0.3em] text-slate-400 uppercase select-none">
                      <span>FRAME_SEQUENCE_ALPHA</span>
                      <span>COLLISION_MASK_V1_4X4</span>
                    </div>

                    <div className="absolute top-8 right-8 opacity-0 group-hover:opacity-100 transition-opacity">
                      <button className="p-3 rounded-lg bg-black/80 backdrop-blur-md border border-white/10 text-white hover:bg-black transition-colors">
                        <Maximize2 className="w-5 h-5" />
                      </button>
                    </div>
                  </motion.div>
                ) : (
                  <motion.div 
                    key="empty"
                    initial={{ opacity: 0 }}
                    animate={{ opacity: 1 }}
                    className="flex flex-col items-center gap-4 text-slate-700"
                  >
                    <div className="w-20 h-20 border-2 border-slate-800 rounded-3xl flex items-center justify-center">
                      <Palette className="w-10 h-10 stroke-[1]" />
                    </div>
                    <p className="text-[10px] font-bold uppercase tracking-widest text-slate-600">Awaiting Input Signal</p>
                  </motion.div>
                )}
              </AnimatePresence>
            </div>
          </div>

          {/* Console/Footer */}
          <footer className="h-12 border-t border-white/5 bg-brand-sidebar px-6 flex items-center justify-between shrink-0 relative z-20">
            <div className="flex items-center gap-5 text-[10px] font-mono">
              <span className="text-green-500 flex items-center gap-1.5 font-bold tracking-tight">
                <span className="w-1.5 h-1.5 rounded-full bg-green-500 animate-pulse shadow-[0_0_8px_rgba(34,197,94,0.6)]"></span>
                SYSTEM_IDLE
              </span>
              <span className="text-slate-800 text-xs">|</span>
              <span className="text-slate-500 uppercase">GPU Acceleration: Enabled</span>
              <span className="text-slate-800 text-xs">|</span>
              <span className="text-slate-400 uppercase tracking-tighter">AI_ENGINE: GEMINI_2.5_FLASH</span>
            </div>
            
            <div className="flex items-center gap-4">
              <div className="flex items-center gap-4">
                <div className="w-32 h-1.5 bg-white/5 rounded-full overflow-hidden">
                  <motion.div 
                    initial={{ width: 0 }}
                    animate={{ width: isGenerating ? `${progress}%` : spriteSheet ? '100%' : '0%' }}
                    className="h-full bg-indigo-500 shadow-[0_0_8px_rgba(99,102,241,0.4)]"
                  />
                </div>
                <span className="text-[9px] text-slate-500 uppercase tracking-[0.2em] font-bold">Progress: {isGenerating ? progress : spriteSheet ? 100 : 0}%</span>
              </div>
              <span className="text-slate-800 text-xs">|</span>
              <span className="text-[9px] text-slate-500 uppercase tracking-widest font-bold">RAM: 1.2GB / 4.0GB</span>
            </div>
          </footer>
        </main>
      </div>
    </div>
  );
}

